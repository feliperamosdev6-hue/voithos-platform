const normalizeTemplate = (template = {}) => ({
  version: TEMPLATE_CATALOG_VERSION,
  month: Number(template.month || 0),
  id: String(template.id || '').trim(),
  title: String(template.title || '').trim() || 'Template',
  description: String(template.description || '').trim(),
  objective: String(template.objective || '').trim(),
  category: String(template.category || 'RELATIONSHIP').trim(),
  segmentType: String(template.segmentType || 'all_active').trim().toLowerCase() || 'all_active',
  segmentSuggestion: String(template.segmentSuggestion || '').trim(),
  priority: String(template.priority || 'MEDIUM').trim().toUpperCase(),
  impact: String(template.impact || template.estimatedConversionImpact || 'MEDIUM').trim().toUpperCase(),
  color: String(template.color || '#2a9d8f').trim() || '#2a9d8f',
  internalCta: String(template.internalCta || 'Abrir fluxo assistido').trim(),
  supportsScheduling: template.supportsScheduling === true,
  messages: {
    short: String(template.messages?.short || '').trim(),
    standard: String(template.messages?.standard || '').trim(),
    humanized: String(template.messages?.humanized || '').trim(),
  },
});

const toClientTemplate = (template = {}) => {
  const normalized = normalizeTemplate(template);
  return {
    ...normalized,
    nome: normalized.title,
    descricao: normalized.description,
    cor: normalized.color,
    cta: normalized.messages.short,
    messageTemplate: normalized.messages.standard,
    baseMessage: normalized.messages.standard,
    estimatedConversionImpact: normalized.impact,
    segmentKey: normalized.segmentType,
  };
};

const listCampaignTemplatesCatalog = ({ month } = {}) => {
  const currentMonth = Math.max(1, Math.min(12, Number(month) || (new Date().getMonth() + 1)));
  const annualTemplates = TEMPLATE_CATALOG.map(toClientTemplate);
  const monthly = annualTemplates.find((item) => item.month === currentMonth) || annualTemplates[0] || null;
  return {
    version: TEMPLATE_CATALOG_VERSION,
    month: currentMonth,
    monthly,
    monthlyCampaignTemplates: annualTemplates,
    annualTemplates,
    quickTemplates: annualTemplates,
  };
};

const getCampaignTemplateById = (templateId) => {
  const normalizedId = String(templateId || '').trim();
  if (!normalizedId) return null;
  return TEMPLATE_CATALOG.map(normalizeTemplate).find((item) => item.id === normalizedId) || null;
};

module.exports = {
  TEMPLATE_CATALOG_VERSION,
  TEMPLATE_CATALOG,
  listCampaignTemplatesCatalog,
  getCampaignTemplateById,
  toClientTemplate,
};
